const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('terp', {
  // サンドボックスの preload では os を読めないため、本体から受け取る
  home: ipcRenderer.sendSync('home'),
  editorWorker: ipcRenderer.sendSync('editor:worker'),
  onCloseRequest: (fn) => ipcRenderer.on('window:close-request', (_e, id) => fn(id)),
  replyClose: (id, answer) => ipcRenderer.send('window:close-reply', id, answer),
  getConfig: () => ipcRenderer.invoke('config:get'),
  rawConfig: () => ipcRenderer.invoke('config:raw'),
  updateConfig: (patch) => ipcRenderer.invoke('config:update', patch),
  listThemes: () => ipcRenderer.invoke('config:themes'),
  openConfigFile: () => ipcRenderer.invoke('config:open-file'),
  loadTabs: () => ipcRenderer.invoke('tabs:load'),
  saveTabs: (state) => ipcRenderer.invoke('tabs:save', state),
  onConfig: (fn) => ipcRenderer.on('config', (_e, config) => fn(config)),
  createPty: (opts) => ipcRenderer.invoke('pty:create', opts),
  restoreInfo: () => ipcRenderer.invoke('pty:restore-info'),
  attach: (id) => ipcRenderer.invoke('pty:attach', id),
  setMeta: (id, meta) => ipcRenderer.send('pty:meta', id, meta),
  shutdownHost: () => ipcRenderer.invoke('pty:shutdown-host'),
  onHostStale: (fn) => ipcRenderer.on('host-stale', () => fn()),
  write: (id, data) => ipcRenderer.send('pty:write', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', id, cols, rows),
  kill: (id) => ipcRenderer.send('pty:kill', id),
  onData: (fn) => ipcRenderer.on('pty:data', (_e, id, data) => fn(id, data)),
  onExit: (fn) => ipcRenderer.on('pty:exit', (_e, id, code) => fn(id, code)),
  onInfo: (fn) => ipcRenderer.on('pty:info', (_e, info) => fn(info)),
  onMenu: (fn) => ipcRenderer.on('menu', (_e, action, arg) => fn(action, arg)),
  listProjects: () => ipcRenderer.invoke('projects:list'),
  addProject: (dir) => ipcRenderer.invoke('projects:add', dir),
  removeProject: (repo) => ipcRenderer.invoke('projects:remove', repo),
  reorderProjects: (order) => ipcRenderer.invoke('projects:reorder', order),
  createWork: (opts) => ipcRenderer.invoke('work:create', opts),
  removeWork: (opts) => ipcRenderer.invoke('work:remove', opts),
  workChanges: (dir) => ipcRenderer.invoke('work:changes', dir),
  filesRoot: (dir) => ipcRenderer.invoke('files:root', dir),
  listFiles: (dir) => ipcRenderer.invoke('files:list', dir),
  readFile: (file) => ipcRenderer.invoke('files:read', file),
  statFile: (file) => ipcRenderer.invoke('files:stat', file),
  writeFile: (opts) => ipcRenderer.invoke('files:write', opts),
  openExternalFile: (file) => ipcRenderer.invoke('files:open-external', file),
  revealFile: (file) => ipcRenderer.invoke('files:reveal', file),
  listAgents: () => ipcRenderer.invoke('agents:list'),
  gitStatus: (dir) => ipcRenderer.invoke('git:status', dir),
  gitDiff: (opts) => ipcRenderer.invoke('git:diff', opts),
  gitStage: (opts) => ipcRenderer.invoke('git:stage', opts),
  gitUnstage: (opts) => ipcRenderer.invoke('git:unstage', opts),
  gitCommit: (opts) => ipcRenderer.invoke('git:commit', opts),
  gitPush: (top) => ipcRenderer.invoke('git:push', top),
  gitPull: (top) => ipcRenderer.invoke('git:pull', top),
  gitFetch: (top) => ipcRenderer.invoke('git:fetch', top),
  openExternal: (url) => ipcRenderer.send('open-external', url),
});
